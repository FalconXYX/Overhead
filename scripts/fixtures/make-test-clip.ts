// scripts/fixtures/make-test-clip.ts — writes the e2e test-pattern clip, tests/fixtures/video/test-pattern.webm (M5 step
// 14.4), and checks it. Run by hand, never in CI:
//   npx tsx scripts/fixtures/make-test-clip.ts [--ffmpeg <path>] [--out tests/fixtures/video/test-pattern.webm]
// Needs an ffmpeg with libvpx-vp9 and lavfi (a static ffmpeg 7.1 arm64 build was used).
//
// The clip: 320 × 180, 25 fps, 7.00 s (175 frames), VP9 in WebM, no audio. Each frame shows four quadrants, top-left
// #ff0000, top-right #00ff00, bottom-left #0000ff, bottom-right #ffffff, and an 8 px black square moving along the
// bottom edge at 80 px/s (x = 80 t mod 320). It is generated by ffmpeg's lavfi sources instead of the milestone file's
// Playwright recordVideo, so it is byte for byte reproducible: one encoder thread, no row multithreading and
// `-fflags +bitexact` (no random segment UID, no version strings); two runs on 2026-10-11 gave identical bytes.
// The tests use only the quadrant colours and the duration, which test-pattern.sidecar.json states (7 s, 25 fps).
import { spawn } from "node:child_process";
import { copyFile, mkdtemp, rm, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

export const TEST_CLIP = {
  widthPx: 320,
  heightPx: 180,
  fps: 25,
  durationS: 7,
  squarePx: 8,
  squareSpeedPxPerS: 80,
} as const;
/** Quadrant colours as #rrggbb: top-left, top-right, bottom-left, bottom-right. */
export const TEST_CLIP_QUADRANTS = ["ff0000", "00ff00", "0000ff", "ffffff"] as const;
const DEFAULT_OUT = "tests/fixtures/video/test-pattern.webm";
const USAGE =
  "usage: npx tsx scripts/fixtures/make-test-clip.ts [--ffmpeg <path>] [--out <file.webm>]";

/** The lavfi graph: four drawbox quadrants on black, and the square overlaid at x = 80 t mod 320 (per frame). */
export function testClipFilterGraph(): string {
  const { widthPx: w, heightPx: h, fps, durationS, squarePx, squareSpeedPxPerS } = TEST_CLIP;
  const hw = w / 2;
  const hh = h / 2;
  const [tl, tr, bl, br] = TEST_CLIP_QUADRANTS;
  const box = (x: number, y: number, color: string): string =>
    `drawbox=x=${x}:y=${y}:w=${hw}:h=${hh}:color=0x${color}:t=fill`;
  return [
    `color=c=black:s=${w}x${h}:r=${fps}:d=${durationS},${box(0, 0, tl)},${box(hw, 0, tr)},${box(0, hh, bl)},${box(hw, hh, br)}[bg]`,
    `color=c=black:s=${squarePx}x${squarePx}:r=${fps}:d=${durationS}[sq]`,
    `[bg][sq]overlay=x='mod(${squareSpeedPxPerS}*t\\,${w})':y=${h - squarePx}:eval=frame,format=yuv420p[v]`,
  ].join(";");
}

/** ffmpeg's arguments: a deterministic VP9 encode of testClipFilterGraph() into outPath. */
export function testClipFfmpegArgs(outPath: string): string[] {
  return [
    "-hide_banner",
    "-loglevel",
    "error",
    "-y",
    "-filter_complex",
    testClipFilterGraph(),
    "-map",
    "[v]",
    "-an",
    "-c:v",
    "libvpx-vp9",
    "-pix_fmt",
    "yuv420p",
    "-b:v",
    "0",
    "-crf",
    "32",
    "-deadline",
    "good",
    "-cpu-used",
    "4",
    "-row-mt",
    "0",
    "-threads",
    "1",
    "-g",
    String(TEST_CLIP.fps), // a keyframe every second: seeks land on the right frame
    "-map_metadata",
    "-1",
    "-fflags",
    "+bitexact",
    "-flags:v",
    "+bitexact",
    outPath,
  ];
}

function run(
  command: string,
  args: readonly string[],
): Promise<{ stdout: Buffer; stderr: string }> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "pipe", "pipe"] });
    const out: Buffer[] = [];
    let stderr = "";
    child.stdout.on("data", (chunk: Buffer) => out.push(chunk));
    child.stderr.on("data", (chunk: Buffer) => {
      stderr += chunk.toString();
    });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) resolve({ stdout: Buffer.concat(out), stderr });
      else reject(new Error(`${command} exited with ${code}: ${stderr.trim()}`));
    });
  });
}

/** Decodes frames 0, 25 and 174 and checks each quadrant centre (within 40 per channel) and the duration. */
async function checkClip(ffmpeg: string, path: string): Promise<void> {
  const { widthPx: w, heightPx: h } = TEST_CLIP;
  const probe = await run(ffmpeg, ["-hide_banner", "-i", path, "-f", "null", "-"]);
  if (!/Duration: 00:00:07\.00,/.test(probe.stderr)) throw new Error("the clip is not 7.00 s long");
  const { stdout } = await run(ffmpeg, [
    ...["-hide_banner", "-loglevel", "error", "-i", path],
    ...["-vf", "select='eq(n\\,0)+eq(n\\,25)+eq(n\\,174)'", "-fps_mode", "passthrough"],
    ...["-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
  ]);
  const frameBytes = w * h * 3;
  if (stdout.length !== 3 * frameBytes) throw new Error("expected 3 decoded frames");
  const centres = [
    [w / 4, h / 4],
    [(3 * w) / 4, h / 4],
    [w / 4, (3 * h) / 4],
    [(3 * w) / 4, (3 * h) / 4],
  ] as const;
  for (let f = 0; f < 3; f++) {
    centres.forEach(([x, y], q) => {
      const at = f * frameBytes + (y * w + x) * 3;
      const hex = TEST_CLIP_QUADRANTS[q] ?? "000000";
      for (let c = 0; c < 3; c++) {
        const want = Number.parseInt(hex.slice(2 * c, 2 * c + 2), 16);
        const got = stdout[at + c] ?? -1;
        if (Math.abs(got - want) > 40)
          throw new Error(`frame ${f}, quadrant ${q}: channel ${c} is ${got}, not ${want}`);
      }
    });
  }
}

async function main(argv: readonly string[]): Promise<void> {
  let ffmpeg = "ffmpeg";
  let out = DEFAULT_OUT;
  for (let i = 0; i < argv.length; i += 2) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (value === undefined) throw new Error(USAGE);
    if (flag === "--ffmpeg") ffmpeg = value;
    else if (flag === "--out") out = value;
    else throw new Error(USAGE);
  }
  const dir = await mkdtemp(join(tmpdir(), "overhead-test-clip-"));
  try {
    const tmp = join(dir, "test-pattern.webm");
    await run(ffmpeg, testClipFfmpegArgs(tmp));
    await checkClip(ffmpeg, tmp);
    await copyFile(tmp, out);
    const { size: bytes } = await stat(out);
    console.log(
      `Wrote ${out}: ${bytes} bytes, ${TEST_CLIP.widthPx} × ${TEST_CLIP.heightPx}, 7.00 s`,
    );
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main(process.argv.slice(2));
}
